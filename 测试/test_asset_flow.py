"""无账号、无网络、无密钥的资产审批流程测试。"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "脚本"))
from asset_flow import (
    流程错误, 审核参考, 参考覆盖完整, 检查是否可生成,
    开始反馈, 添加反馈, 截止归纳, 继承并修订元素,
    发布图片版本, 标记无需修改, 终稿确认, 同步顺场图
)


class 资产流程测试(unittest.TestCase):
    def setUp(self):
        self.资产 = {
            "资产编号": "C001", "大类": "人物", "当前版本": "待生成",
            "当前资产图": "", "状态": "参考审核中", "允许生成": False,
            "必需参考部位": ["服装", "面部"],
            "参考素材": [
                {"参考编号":"甲","应用部位":["服装"],"提取元素":["高领"],"审批":"待审核"},
                {"参考编号":"乙","应用部位":["面部"],"提取元素":["冷艳妆容"],"审批":"待审核"}
            ],
            "当前采用元素": [], "历史版本": [], "反馈": []
        }

    def _初版(self):
        结果 = 审核参考(self.资产, "甲", "通过")
        结果 = 审核参考(结果, "乙", "通过")
        结果["允许生成"] = True
        return 发布图片版本(结果, "附件://C001_初版")

    def test_没通过参考不能生成(self):
        self.assertFalse(检查是否可生成(self.资产))
        with self.assertRaises(流程错误):
            发布图片版本(self.资产, "附件://虚构")

    def test_否决必须有原因(self):
        with self.assertRaises(流程错误):
            审核参考(self.资产, "甲", "否决")
        结果 = 审核参考(self.资产, "甲", "否决", "服装风格不对")
        self.assertNotIn("高领", 结果["当前采用元素"])

    def test_参考通过不代表可以生成(self):
        结果 = 审核参考(审核参考(self.资产, "甲", "通过"), "乙", "通过")
        self.assertTrue(参考覆盖完整(结果))
        self.assertFalse(检查是否可生成(结果))

    def test_从旧图生成精修版本且继承元素(self):
        结果 = self._初版()
        结果 = 开始反馈(结果, "2026-11-20T18:00:00+08:00", "需要修改")
        结果 = 添加反馈(结果, "成员甲", "调整妆容", "2026-11-20T17:00:00+08:00")
        with self.assertRaises(流程错误):
            截止归纳(结果, "2026-11-20T17:30:00+08:00")
        结果 = 截止归纳(结果, "2026-11-20T18:00:00+08:00")
        修订 = 继承并修订元素(
            结果["当前采用元素"], 强化={"冷艳妆容":"更冷艳的眼妆"}, 新增=["均匀平光"])
        结果 = 发布图片版本(结果, "附件://C001_1修", 版本修订=修订)
        self.assertEqual(结果["当前版本"], "1修")
        self.assertEqual(结果["历史版本"][0]["版本"], "初版")
        self.assertIn("高领", 结果["当前采用元素"])
        self.assertIn("更冷艳的眼妆", 结果["当前采用元素"])

    def test_反馈截止必须含时区(self):
        with self.assertRaises(流程错误):
            开始反馈(self._初版(), "2026-11-20T18:00:00", "需要修改")

    def test_终稿按钮必须单独点击(self):
        结果 = self._初版()
        with self.assertRaises(流程错误):
            终稿确认(结果, "可以了")
        结果 = 标记无需修改(结果, "无需修改")
        结果 = 终稿确认(结果, "确认终稿")
        self.assertEqual(结果["当前版本"], "终稿")
        with self.assertRaises(流程错误):
            开始反馈(结果, "2026-11-20T18:00:00+08:00", "需要修改")

    def test_撤回参考后元素同步撤回(self):
        结果 = 审核参考(self.资产, "甲", "通过")
        结果 = 审核参考(结果, "甲", "否决", "需要重找")
        self.assertNotIn("高领", 结果["当前采用元素"])

    def test_顺场显示当前图并报告缺失(self):
        结果 = 同步顺场图(
            [self._初版()], [{"集数": 1, "场次": 1, "资产编号列表":["C001", "S001"]}])
        self.assertEqual(结果[0]["自动插入资产"][0]["当前版本"], "初版")
        self.assertEqual(结果[0]["缺失资产"], ["S001"])


if __name__ == "__main__":
    unittest.main()
